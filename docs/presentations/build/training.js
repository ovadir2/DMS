const TW = 13.33;
function head(t, sub, bg) {
  s = pres.addSlide(); s.background = { color: bg || C.white };
  s.addText(t, he({ x: 0.6, y: 0.4, w: 12.1, h: 0.7, fontSize: 32, bold: true, color: C.ink, align: 'right', margin: 0 }));
  if (sub) s.addText(sub, he({ x: 0.6, y: 1.08, w: 12.1, h: 0.4, fontSize: 15, color: C.muted, align: 'right', margin: 0 }));
}
function badge(x, y, n, col, d) {
  d = d || 0.46;
  s.addShape(pres.shapes.OVAL, { x, y, w: d, h: d, fill: { color: col || C.accent }, line: { color: col || C.accent } });
  s.addText(String(n), { x, y, w: d, h: d, fontSize: 14, bold: true, color: C.white, fontFace: F, align: 'center', valign: 'middle', margin: 0, isTextBox: true });
}
// cards in a grid, filled right to left
function grid(items, cols, y0, h, opts) {
  opts = opts || {};
  const gap = 0.3, w = (12.1 - gap * (cols - 1)) / cols;
  items.forEach(([t, b, tag], i) => {
    const r = Math.floor(i / cols), c = i % cols, x = 0.6 + (cols - 1 - c) * (w + gap), y = y0 + r * (h + gap);
    s.addShape(pres.shapes.ROUNDED_RECTANGLE, { x, y, w, h, rectRadius: 0.08, fill: { color: C.white }, line: { color: C.line, width: 1 } });
    badge(x + w - 0.62, y + 0.2, tag || i + 1, opts.colors ? opts.colors[i] : C.accent, 0.42);
    s.addText(t, he({ x: x + 0.2, y: y + 0.2, w: w - 0.95, h: 0.42, fontSize: 16, bold: true, color: C.ink, align: 'right', valign: 'middle', margin: 0 }));
    s.addText(b, he({ x: x + 0.2, y: y + 0.72, w: w - 0.4, h: h - 0.85, fontSize: opts.size || 13, color: C.muted, align: 'right', valign: 'top', margin: 0 }));
  });
}
// numbered steps right to left with arrows (←)
function steps(items, y, h) {
  const n = items.length, gap = 0.42, w = (12.1 - gap * (n - 1)) / n;
  items.forEach(([t, b], i) => {
    const x = 0.6 + (n - 1 - i) * (w + gap);
    s.addShape(pres.shapes.ROUNDED_RECTANGLE, { x, y, w, h, rectRadius: 0.08, fill: { color: i === 0 ? C.soft : C.white }, line: { color: C.accent, width: 1.25 } });
    badge(x + w / 2 - 0.23, y - 0.23, i + 1);
    s.addText([{ text: t, options: { bold: true, fontSize: 15, color: C.ink, breakLine: true } }, { text: b, options: { fontSize: 12, color: C.muted } }],
      he({ x: x + 0.15, y: y + 0.35, w: w - 0.3, h: h - 0.45, align: 'right', valign: 'top', margin: 0 }));
    if (i < n - 1) s.addText('←', { x: x - gap, y: y + h / 2 - 0.25, w: gap, h: 0.5, fontSize: 22, bold: true, color: C.accent, fontFace: F, align: 'center', valign: 'middle', margin: 0, isTextBox: true });
  });
}
function note(t, y, col, fill) {
  s.addShape(pres.shapes.ROUNDED_RECTANGLE, { x: 0.6, y, w: 12.1, h: 0.62, rectRadius: 0.08, fill: { color: fill || C.soft }, line: { color: fill || C.soft } });
  s.addText(t, he({ x: 0.8, y, w: 11.7, h: 0.62, fontSize: 13, color: col || C.ink, align: 'right', valign: 'middle', margin: 0 }));
}
const tbl = (rows, colW, y, size) => {
  const hdr2 = o => Object.assign({ bold: true, color: C.white, fill: { color: C.accent } }, o);
  const data = rows.map((r, i) => r.map(c => ({ text: c, options: i === 0 ? hdr2() : {} })));
  s.addTable(data, { x: 0.6, y, w: 12.1, colW, fontFace: F, fontSize: size || 13, color: C.ink, align: 'right', rtlMode: true, lang: 'he-IL',
    border: { type: 'solid', color: C.line, pt: 1 }, fill: { color: C.white }, valign: 'middle', margin: [4, 8, 4, 8] });
};

